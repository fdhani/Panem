import { posix } from "node:path";

/**
 * Parse devcontainer.json as JSONC: comments and trailing commas allowed, as the devcontainer
 * tooling does. Strings are left alone (a "//" inside one is not a comment).
 */
export function parseJsonc(text: string): unknown {
  let out = "";
  let i = 0;
  while (i < text.length) {
    const c = text[i]!;
    const next = text[i + 1];
    if (c === '"') {
      let j = i + 1;
      while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1;
      out += text.slice(i, j + 1);
      i = j + 1;
    } else if (c === "/" && next === "/") {
      while (i < text.length && text[i] !== "\n") i++;
    } else if (c === "/" && next === "*") {
      const end = text.indexOf("*/", i + 2);
      i = end < 0 ? text.length : end + 2;
    } else {
      out += c;
      i++;
    }
  }
  // Trailing commas before } or ] (outside strings, which are intact above).
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

/** Feature keys Panem delivers: "./panem-features/<id>". */
const PANEM_FEATURE = /^\.\/panem-features\/([A-Za-z0-9_-]+)\/?$/;

const relative = (p: unknown) =>
  typeof p === "string" && !posix.isAbsolute(p) && !/^[a-z]+:\/\//i.test(p);
/** A path relative to .devcontainer/, seen from .devcontainer/panem-features/. */
const up = (p: string) => posix.normalize(posix.join("..", p));

/**
 * The config DevPod is given for a template whose devcontainer.json lists Panem's Features:
 * the same config, moved into .devcontainer/panem-features/ (relative paths adjusted), with
 * `panemBuild: <build>` on each of Panem's Features. DevPod's image cache key includes Feature
 * options but not a local Feature's files, so a new build value means a new image. Returns
 * undefined when the template doesn't list any of Panem's Features.
 */
export function derivedConfig(
  raw: string,
  build: string,
  extra: { mounts?: unknown[] } = {},
): { json: string; ids: string[] } | undefined {
  const cfg = parseJsonc(raw) as Record<string, unknown>;
  const features = (cfg.features ?? {}) as Record<string, unknown>;
  const ids: string[] = [];
  const rewritten: Record<string, unknown> = {};
  for (const [key, opts] of Object.entries(features)) {
    const m = PANEM_FEATURE.exec(key);
    if (m) {
      ids.push(m[1]!);
      const o = typeof opts === "object" && opts !== null ? opts : {};
      rewritten[`./${m[1]}`] = { ...o, panemBuild: build };
    } else if (key.startsWith("./") || key.startsWith("../")) {
      rewritten[up(key).replace(/^(?!\.)/, "./")] = opts;
    } else {
      rewritten[key] = opts;
    }
  }
  if (ids.length === 0) return undefined;
  const out: Record<string, unknown> = { ...cfg, features: rewritten };
  for (const k of ["dockerFile", "context"]) if (relative(out[k])) out[k] = up(out[k] as string);
  if (typeof out.build === "object" && out.build !== null) {
    const b = { ...(out.build as Record<string, unknown>) };
    for (const k of ["dockerfile", "context"]) if (relative(b[k])) b[k] = up(b[k] as string);
    out.build = b;
  }
  if (relative(out.dockerComposeFile)) out.dockerComposeFile = up(out.dockerComposeFile as string);
  if (Array.isArray(out.dockerComposeFile)) {
    out.dockerComposeFile = out.dockerComposeFile.map((p) => (relative(p) ? up(p as string) : p));
  }
  if (extra.mounts?.length) out.mounts = [...((out.mounts as unknown[]) ?? []), ...extra.mounts];
  return {
    json: `${JSON.stringify(
      { "//": "Generated by Panem at each summon from ../devcontainer.json. Don't edit.", ...out },
      null,
      2,
    )}\n`,
    ids,
  };
}
